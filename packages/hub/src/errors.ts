export const HUB_ERROR_CODES = {
  PROTOCOL_INVALID_MESSAGE: "PROTOCOL_INVALID_MESSAGE",
  PROTOCOL_UNKNOWN_MESSAGE_TYPE: "PROTOCOL_UNKNOWN_MESSAGE_TYPE",
  SESSION_NOT_FOUND: "SESSION_NOT_FOUND",
  SESSION_CONNECTION_MISMATCH: "SESSION_CONNECTION_MISMATCH",
  SESSION_REVOKED: "SESSION_REVOKED",
  SESSION_NOT_ACTIVE: "SESSION_NOT_ACTIVE",
  KILL_SWITCH_DISABLED: "KILL_SWITCH_DISABLED",
  WAITING_ROOM_DECISION_REQUIRED: "WAITING_ROOM_DECISION_REQUIRED",
  WAITING_ROOM_ENTRY_NOT_FOUND: "WAITING_ROOM_ENTRY_NOT_FOUND",
  EXTENSION_UNAVAILABLE: "EXTENSION_UNAVAILABLE",
  ROUTING_FAILED: "ROUTING_FAILED",
} as const;

export type HubErrorCode =
  (typeof HUB_ERROR_CODES)[keyof typeof HUB_ERROR_CODES];

export class HubError extends Error {
  readonly errorCode: HubErrorCode;

  constructor(message: string, errorCode: HubErrorCode) {
    super(message);
    this.name = "HubError";
    this.errorCode = errorCode;
  }
}
